/// Fail loudly when a window stops decoding early.
///
/// Every lifter here stops at the first byte it cannot decode and returns what
/// it had, so a mis-assembled constant would silently turn into a benchmark of
/// two instructions and a bail-out. Requiring the last lifted instruction to
/// start within `slack` bytes of the end of the window makes that a panic in
/// setup instead of a plausible-looking number.
fn assert_window_fully_lifted(
    id: &str,
    bytes: &[u8],
    lifted: &[glaurung::ir::LlirInstr],
    slack: u64,
) {
    let last = lifted
        .last()
        .unwrap_or_else(|| panic!("{id}: window lifted to nothing"))
        .va;
    let covered = last - MICRO_VA;
    assert!(
        covered + slack >= bytes.len() as u64,
        "{id}: decoding stopped at +{covered:#x} of a {:#x}-byte window",
        bytes.len()
    );
}

