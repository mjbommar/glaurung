//! Criterion benchmarks for the LLIR instruction lifters.
//!
//! The lifters are the largest and hottest modules in the tree — `lift_x86` is
//! ~9.5k LOC, `lift_arm32` ~3.9k, `lift_arm64` ~3.6k, `x87` ~1.7k — and every
//! decompile pays for them once per byte of code it recovers. These benchmarks
//! measure them at two tiers, because the two answer different questions:
//!
//! * **Micro** (`ir_lift/micro/*`) lifts a fixed, hand-assembled window of one
//!   instruction *shape* per benchmark: plain register ALU, memory operands with
//!   SIB and displacement, control flow, SSE, AVX, x87, ARM predication, AArch64
//!   addressing modes. These isolate the cost of a decode+lower step so a change
//!   to one operand path shows up instead of being averaged away. The byte slices
//!   below were produced by `as`/`aarch64-linux-gnu-as`/`arm-linux-gnueabihf-as`
//!   from the assembly quoted in each doc comment — they are the input format the
//!   lifter takes, not synthetic stand-ins for it.
//! * **Per-function** (`ir_lift/function/*`, `ir_lift/binary/*`) runs
//!   [`lift_function_from_image`] over real functions recovered from the
//!   prebuilt decompiler fixtures, which is the shape the pipeline actually
//!   calls. Discovery (`analyze_functions_image`) runs once during setup and is
//!   *not* timed; only the lift is.
//!
//! Throughput is declared everywhere a size is meaningful: bytes of machine code
//! for the windows and the per-function lanes, functions for the whole-binary
//! lanes, so criterion reports MiB/s and functions/s rather than bare latencies.
//!
//! Not benchmarked here, and why: `ir::canary`, `ir::arm32_prologue` and
//! `ir::arm64_prologue` are public but consume `ir::ast::Function`, which is a
//! *post*-lift artifact built only by the decompile pipeline in
//! `src/python_bindings/ir/pipeline.rs` (behind the `python-ext` feature). There
//! is no public constructor for one, so they belong to the pipeline benchmark
//! rather than to this file. `lift_x86::lift_bytes_with_x87` is `pub(crate)`;
//! the `ir_lift/micro/x86/x86_64-x87` lane reaches it through `lift_bytes`, and
//! `ir_lift/micro/x87/plan_window` times the depth resolution on its own.

