/// One binary's functions, discovered once and reused by every lane over it.
struct Corpus {
    label: String,
    image: ProgramImage,
    /// Ascending by lifted code size, then by entry VA to break ties.
    functions: Vec<Function>,
}

fn manifest_path(relative: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(relative)
}

/// Discover every liftable function in `relative`, outside the measured region.
///
/// The per-function `timeout_ms` is raised well above its 100 ms default: a
/// truncated CFG walk would change *which* functions the benchmark IDs name
/// depending on how loaded the machine was when it started, and a benchmark
/// whose identity drifts is worse than one that takes longer to set up.
fn load_corpus(label: &str, relative: &str) -> Option<Corpus> {
    let path = manifest_path(relative);
    if !path.exists() {
        eprintln!("ir_lift: skipping {label} — {} is absent", path.display());
        return None;
    }
    let image = match ProgramImage::from_path(&path) {
        Ok(image) => image,
        Err(err) => {
            eprintln!(
                "ir_lift: skipping {label} — {} could not be indexed: {err:?}",
                path.display()
            );
            return None;
        }
    };
    let budgets = Budgets {
        timeout_ms: 5_000,
        ..Budgets::default()
    };
    let (mut functions, _call_graph) = analyze_functions_image(&image, &budgets);
    // A function the lifter rejects (unsupported arch, incoherent code mode, no
    // owned blocks) would time an error path, not a lift. Nothing else is
    // filtered here: the `ir_lift/binary` lane is supposed to be the whole
    // object, so the size floor and the CRT exclusion belong to the per-function
    // picker instead.
    functions.retain(|f| {
        !f.basic_blocks.is_empty()
            && f.total_size() > 0
            && lift_function_from_image(&image, f).is_ok_and(|lf| !lf.blocks.is_empty())
    });
    if functions.is_empty() {
        eprintln!("ir_lift: skipping {label} — no liftable functions were discovered");
        return None;
    }
    functions.sort_by_key(|f| (f.total_size(), f.entry_point.value));
    Some(Corpus {
        label: label.to_string(),
        image,
        functions,
    })
}

/// Criterion turns benchmark IDs into directory names, so C++ mangling and the
/// `.` in `.cold` parts have to go.
fn sanitize(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|ch| if ch.is_ascii_alphanumeric() { ch } else { '_' })
        .collect();
    // Mangled C++ names run to hundreds of characters; the entry VA in the
    // caller's label is what disambiguates, not the tail of the symbol.
    cleaned.chars().take(48).collect()
}

/// The C-runtime stubs every ELF the toolchain links carries.
///
/// They are real code and the `ir_lift/binary` lanes still lift them, but they
/// are byte-identical across all six fixtures, so letting them win the "small"
/// slot would spend six benchmarks measuring one 40-byte function instead of
/// the compiled fixture bodies this tier exists for.
const CRT_STUBS: &[&str] = &[
    "_start",
    "_init",
    "_fini",
    "call_weak_fn",
    "deregister_tm_clones",
    "register_tm_clones",
    "__do_global_dtors_aux",
    "frame_dummy",
    "__libc_csu_init",
    "__libc_csu_fini",
    "__stack_chk_fail_local",
    "atexit",
];

/// Smallest, median and largest interesting function, as `(role, index)`.
///
/// "Interesting" excludes the CRT stubs and anything under 32 bytes — a
/// four-instruction thunk measures the per-call setup of
/// `lift_function_from_image`, not the lifting. Falls back to the unfiltered
/// list when that leaves nothing, so a stripped or unusual object still gets a
/// lane. Duplicate indices collapse, which is what makes a two-function binary
/// produce two benchmarks rather than three names for the same work.
fn size_spread(corpus: &Corpus) -> Vec<(&'static str, usize)> {
    let mut candidates: Vec<usize> = corpus
        .functions
        .iter()
        .enumerate()
        .filter(|(_, f)| f.total_size() >= 32 && !CRT_STUBS.contains(&f.name.as_str()))
        .map(|(index, _)| index)
        .collect();
    if candidates.is_empty() {
        candidates = (0..corpus.functions.len()).collect();
    }
    let last = candidates.len() - 1;
    let mut picked = vec![
        ("small", candidates[0]),
        ("mid", candidates[last / 2]),
        ("large", candidates[last]),
    ];
    // Ascending, so equal indices are adjacent and this removes every repeat.
    picked.dedup_by_key(|(_, index)| *index);
    picked
}

fn bench_functions(c: &mut Criterion, corpora: &[Corpus]) {
    let mut group = c.benchmark_group("ir_lift/function");
    for corpus in corpora {
        for (role, index) in size_spread(corpus) {
            let func = &corpus.functions[index];
            let id = BenchmarkId::new(&corpus.label, format!("{role}-{}", sanitize(&func.name)));
            group.throughput(Throughput::Bytes(func.total_size()));
            group.bench_function(id, |b| {
                b.iter(|| lift_function_from_image(black_box(&corpus.image), black_box(func)))
            });
        }
    }
    group.finish();
}

