def test_generator_batches_real_fixtures_deterministically(tmp_path):
    """A filtered batch must agree across serial and parallel scheduling."""
    objects = (
        "02_integer_widths-clang-O2.so",
        "02_integer_widths-gcc-O2.so",
    )
    for obj in objects:
        _require_corpus(obj)

    outputs = []
    checkpoint = tmp_path / "objects.jsonl"
    for jobs in (1, 2):
        output = tmp_path / f"jobs-{jobs}.json"
        argv = ["--jobs", str(jobs), "--no-progress", "--output", str(output)]
        if jobs == 1:
            argv.extend(("--checkpoint", str(checkpoint)))
        for obj in objects:
            argv.extend(("--fixture", obj))
        assert G.main(argv) == 0
        payload = json.loads(output.read_text())
        assert payload["objects_scanned"] == 2
        assert all(row["obj"] in objects for axis in G.AXES for row in payload[axis])
        payload.pop("elapsed_seconds")
        outputs.append(payload)
    assert outputs[0] == outputs[1]

    resumed = tmp_path / "resumed.json"
    argv = [
        "--jobs",
        "2",
        "--no-progress",
        "--checkpoint",
        str(checkpoint),
        "--resume",
        "--output",
        str(resumed),
    ]
    for obj in objects:
        argv.extend(("--fixture", obj))
    assert G.main(argv) == 0
    payload = json.loads(resumed.read_text())
    payload.pop("elapsed_seconds")
    assert payload == outputs[0]
    assert len(checkpoint.read_text().splitlines()) == 2


def test_generated_inventory_summaries_are_current():
    """Committed summary metadata must match the measured row inventory."""
    rows = {axis: _rows(axis) for axis in G.AXES}
    by_language, deduplicated, deduplicated_by_language = G.inventory_summaries(rows)
    assert _summary("counts_by_language") == by_language
    assert _summary("deduplicated_counts") == deduplicated
    assert _summary("deduplicated_counts_by_language") == deduplicated_by_language
    counts = _counts()
    assert sum(v for k, v in counts.items() if k != "goto_statements") == 874, (
        f"the inventory records only {counts}; it should hold the 874 "
        "failures the corpus demonstrates. An empty inventory makes this whole "
        "file silently vacuous."
    )
    weak_fold = [
        row
        for row in rows["structure"]
        if row["obj"] == "158_weak_symbols-gcc-O2.so" and row["fn"] == "weak_fold"
    ]
    assert [row["gotos"] for row in weak_fold] == [2], (
        "shared return-tail ownership must not replace weak_fold's two direct "
        "loop-exit returns with extra gotos"
    )


@pytest.mark.parametrize("row", list(_type_params()))
def test_recovered_prototype_matches_dwarf(row):
    """The recovered parameter type must match what the compiler recorded."""
    _require_corpus(row["obj"])
    text = _render(row["obj"], row["va"])
    assert text, f"{row['obj']}::{row['fn']} produced no body"
    sig = _signature_of(text)
    assert sig, f"no signature line:\n{text[:200]}"
    decls = G.split_params(sig)
    assert decls is not None, sig
    assert row["arg"] < len(decls), f"arg{row['arg']} beyond {sig}"
    got = G.classify(G.strip_name(decls[row["arg"]]))["raw"]
    assert got != row["got"], (
        f"{row['fn']} arg{row['arg']} still recovers as `{row['got']}`"
    )


@pytest.mark.parametrize("row", list(_structure_params()))
def test_goto_free_source_recovers_without_goto(row):
    """Source with no `goto` must not recover with one."""
    _require_corpus(row["obj"])
    text = _render(row["obj"], row["va"])
    assert text, f"{row['obj']}::{row['fn']} produced no body"
    gotos = re.findall(r"\bgoto\s+\w+\s*;", text)
    assert not gotos, f"{len(gotos)} goto statement(s) in {row['fn']}"


def test_the_failure_count_does_not_grow():
    """The ratchet over the whole corpus.

    Individual xfails catch a fix; this catches a regression that adds NEW
    failures, which would otherwise appear as entries nobody recorded.
    """
    counts = _counts()
    assert counts.get("types", 0) <= 82, (
        f"prototype mismatches grew to {counts.get('types')} (recorded 82)"
    )
    assert counts.get("structure", 0) <= 715, (
        f"functions with unwanted goto grew to {counts.get('structure')} (recorded 715)"
    )
    assert counts.get("goto_statements", 0) <= 6825, (
        f"goto statements grew to {counts.get('goto_statements')} (recorded 6,825)"
    )
    assert counts.get("returns", 0) <= 41, (
        f"return-type mismatches grew to {counts.get('returns')} (recorded 41)"
    )
    assert counts.get("unrecovered", 0) <= 42, (
        f"unrecovered constructs grew to {counts.get('unrecovered')} (recorded 42)"
    )
    # These two are ZERO today, which is worth pinning as an achievement
    # rather than leaving as an absence: a DWARF pointer parameter never
    # degrades to a scalar, and every function DWARF names produces a body.
    assert counts.get("pointers", 0) == 0, (
        f"{counts.get('pointers')} pointer parameter(s) now recover as scalars; "
        "recovered C would dereference an integer"
    )
    assert counts.get("no_body", 0) == 0, (
        f"{counts.get('no_body')} function(s) DWARF names now produce no body"
    )
