"""Every decompiler failure the fixture corpus can currently demonstrate.

**874 of them**, measured rather than asserted, each one a strict xfail that
turns red the day it is fixed.

Why this file
-------------

A suite that is green over a decompiler with known trade-offs is not measuring
the trade-offs. Before this, the estate could tell you that output *behaved*
correctly (the execution differential) and roughly how *readable* it was in
aggregate (the readability census), but it could not name a single function
whose recovered prototype disagreed with the source, and it could not name the
713 functions that emit `goto` for source containing none.

Two axes, both against ground truth rather than against yesterday's output:

**types** (82) — the recovered prototype versus the DWARF the compiler
emitted. DWARF states the source signature exactly, so a disagreement is a
recovery gap, not a stylistic choice. 72 are signedness, 10 are width.

**structure** (713, totalling 6,823 `goto` statements) — a `goto` in recovered
C for a function whose source file contains no `goto` anywhere. This is the
class `docs/development/decompiler-parity-backlog.md` measures at 28.8% of
scored DecBench functions, and the execution differential is blind to it by
construction: goto soup is faithful, compiles, and returns the right answer for
every input. It simply is not the control flow the programmer wrote.

How it behaves
--------------

Each entry asserts the CORRECT behaviour under
`@pytest.mark.xfail(strict=True)`. Today they xfail and the report names them.
When one is fixed it XPASSes, strict turns that red, and the message says to
regenerate the inventory — so an improvement announces itself instead of
sliding by. That is the opposite of pinning current output, which makes a fix
indistinguishable from a regression.

The inventory is `tests/open_defects/known_failures.json`, regenerated by
`tools/gen_known_failures.py` (44.6 seconds over 1,676 objects with eight bounded
workers on the recorded 2026-09-05 run). It is evidence, not configuration: do
not hand-edit it.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent.parent
BUILD = ROOT / "tests" / "decompiler_fixtures" / "build"
INVENTORY = ROOT / "tests" / "open_defects" / "known_failures.json"
sys.path.insert(0, str(ROOT / "tools"))

import diff_decompile as D  # ty: ignore[unresolved-import]  # added above

# The SAME parameter splitter and type classifier the inventory was built with.
# Re-implementing them here is how the first version produced 36 spurious
# XPASSes: a naive `split(",")` disagrees with the generator's depth-aware
# split on any signature containing nested parentheses, so the two disagreed
# about which parameter `arg2` even is.
import gen_known_failures as G  # ty: ignore[unresolved-import]  # added above

#: The measured inventory. Typed explicitly because `json.loads` returns
#: `Any | list | dict`, so every `.get` below is an unresolved-attribute error
#: against the list arm until the union is narrowed.
_DATA: dict[str, object] = (
    json.loads(INVENTORY.read_text())
    if INVENTORY.is_file()
    else {"types": [], "structure": [], "counts": {}}
)


def _rows(key: str) -> list[dict]:
    value = _DATA.get(key, [])
    return value if isinstance(value, list) else []


def _counts() -> dict:
    value = _DATA.get("counts", {})
    return value if isinstance(value, dict) else {}


def _summary(name: str) -> dict:
    value = _DATA.get(name, {})
    return value if isinstance(value, dict) else {}


#: One native batch per object, shared across every inventory axis.  The old
#: cache avoided duplicate rows only after starting one CLI process per
#: function; on Rust runtime-heavy objects that still made this test file take
#: hours.  Keep the batch keyed by VA because closure names are not unique.
_OBJECT_CACHE: dict[str, dict[int, str]] = {}


def _inventory_vas(obj: str) -> list[int]:
    """All authoritative entry addresses this test file needs from an object."""
    return list(
        dict.fromkeys(
            int(row["va"])
            for axis in G.AXES
            for row in _rows(axis)
            if row["obj"] == obj
        )
    )


def _render(obj: str, va: int) -> str | None:
    """Decompile an object's required VAs together, never by name.

    Rust emits many functions called `{closure#0}`; a name-keyed lookup takes
    whichever one `signatures()` yields first, which is how the first version
    of this file produced 41 spurious XPASSes on rust fixtures.
    """
    if obj not in _OBJECT_CACHE:
        path = BUILD / obj
        recovered = {}
        if path.is_file():
            try:
                recovered = D.decompiled_many_c(str(path), _inventory_vas(obj))
            except Exception:
                recovered = {}
        _OBJECT_CACHE[obj] = recovered
    return _OBJECT_CACHE[obj].get(int(va))


def _require_corpus(obj: str) -> None:
    if not BUILD.is_dir():
        pytest.skip(
            f"{BUILD.relative_to(ROOT)} is gitignored and absent; build the "
            "fixture matrix to run the known-failure corpus"
        )
    if not (BUILD / obj).is_file():
        pytest.skip(f"{obj} not built in this checkout")


def _signature_of(text: str) -> str | None:
    for line in text.splitlines():
        if line.startswith("//") or not line.strip():
            continue
        if "(" in line:
            return line.split("{")[0].strip()
    return None


def _type_params():
    for r in _rows("types"):
        want = f"width {r['want']} bytes" if r["kind"] == "width" else str(r["want"])
        yield pytest.param(
            r,
            id=f"{r['obj']}::{r['fn']}@{r['va']:#x}::arg{r['arg']}::{r['kind']}",
            marks=pytest.mark.xfail(
                strict=True,
                reason=(
                    f"OPEN DEFECT (prototype {r['kind']}): {r['fn']} arg{r['arg']} "
                    f"is {want} in the DWARF the compiler emitted, recovered as "
                    f"`{r['got']}`. Ground truth, not preference."
                ),
            ),
        )


def _structure_params():
    for r in _rows("structure"):
        yield pytest.param(
            r,
            id=f"{r['obj']}::{r['fn']}@{r['va']:#x}::goto",
            marks=pytest.mark.xfail(
                strict=True,
                reason=(
                    f"OPEN DEFECT (structuring): {r['fn']} emits {r['gotos']} "
                    "`goto` statement(s) for a source file containing none. The "
                    "execution differential passes it -- goto soup is faithful, "
                    "compiles and returns the right answer; it is simply not the "
                    "control flow that was written."
                ),
            ),
        )


def _return_params():
    for r in _rows("returns"):
        want = "a pointer" if r["kind"] == "ptr_lost" else f"{r['want']} bytes wide"
        yield pytest.param(
            r,
            id=f"{r['obj']}::{r['fn']}@{r['va']:#x}::return::{r['kind']}",
            marks=pytest.mark.xfail(
                strict=True,
                reason=(
                    f"OPEN DEFECT (return type): {r['fn']} returns {want} in "
                    f"DWARF, recovered as `{r['got']}`. A wrong return type is "
                    "what makes a function look `void` -- the shape both the "
                    "-flto collapse and the AArch64 FMA gap produce."
                ),
            ),
        )


def _unrecovered_params():
    for r in _rows("unrecovered"):
        yield pytest.param(
            r,
            id=f"{r['obj']}::{r['fn']}@{r['va']:#x}::unrecovered",
            marks=pytest.mark.xfail(
                strict=True,
                reason=(
                    f"OPEN DEFECT (unrecovered construct): {r['fn']} emits "
                    f"{r['n']} `unrecovered` marker(s) -- the renderer stating "
                    "outright that it could not model something. Unlike goto "
                    "soup this is not even faithful-but-ugly; it is a hole."
                ),
            ),
        )


@pytest.mark.parametrize("row", list(_return_params()))
def test_recovered_return_type_matches_dwarf(row):
    """The return type the compiler recorded must survive recovery."""
    _require_corpus(row["obj"])
    text = _render(row["obj"], row["va"])
    assert text, f"{row['obj']}::{row['fn']} produced no body"
    sig = _signature_of(text)
    assert sig, f"no signature line:\n{text[:200]}"
    head = sig.split("(")[0]
    got = G.classify(head.rsplit(" ", 1)[0])["raw"] if " " in head else head
    assert got != row["got"], f"{row['fn']} still returns `{row['got']}`"


@pytest.mark.parametrize("row", list(_unrecovered_params()))
def test_no_unrecovered_construct_remains(row):
    """`unrecovered` in the output is the renderer conceding a hole."""
    _require_corpus(row["obj"])
    text = _render(row["obj"], row["va"])
    assert text, f"{row['obj']}::{row['fn']} produced no body"
    hits = [ln.strip() for ln in text.splitlines() if "unrecovered" in ln]
    assert not hits, f"{len(hits)} unrecovered construct(s):\n  " + "\n  ".join(
        hits[:3]
    )


