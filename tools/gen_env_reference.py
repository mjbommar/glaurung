#!/usr/bin/env python3
"""Generate the environment-variable reference from a grep over the tree.

`docs/reference/environment-variables.md` used to not exist at all: the
~40 `GLAURUNG_*`/`DECBENCH_*`/`AXEYUM_*`/`IOCTLANCE_*`/`BITWUZLA_*` vars this
codebase reads were scattered across Python, Rust, shell scripts and CI YAML
with no single index, and (per `docs/history/docs-rewrite-2026-09/audit/`
ledger 01 #85) `CLAUDE.md` named one, `GLAURUNG_AGENT_ROUTE`, that appears
nowhere in code. This generator walks the tree itself -- no `rg` subprocess,
so it works offline and its result is exactly what the regexes below say it
is -- and reports every variable actually read, with the sites that read it.
An unrecognized name is not hidden; it is marked
"(undocumented -- add to PURPOSES in the generator)" so the gap stays
visible instead of silently passing.

What counts as a "read"
------------------------

* Python: `os.environ["X"]` (not an assignment), `os.environ.get("X", ...)`,
  `os.getenv("X", ...)`.
* Rust: `env::var("X")` / `env::var_os("X")` (with or without the `std::`
  prefix), `option_env!("X")`.
* A one-hop constant indirection in both languages: `ENV_NAME = "X"` /
  `const ENV_NAME: &str = "X";` followed by `os.environ.get(ENV_NAME)` /
  `env::var(ENV_NAME)` elsewhere in the scanned tree. Several real vars are
  only reachable this way, e.g. `python/glaurung/windows_config.py`'s
  `ENV_CONFIG_PATH = "GLAURUNG_WINDOWS_ANALYSIS_CONFIG"` and every
  `*_ENV` constant in `src/symbolic/solver/axeyum_backend.rs`.
* A GitHub Actions workflow `env:` block's direct child keys (how
  `GLAURUNG_REQUIRE_TOOLCHAINS`, `GLAURUNG_FIXTURE_TMPDIR` and friends
  actually reach the process environment in CI).

`build.rs` (repo root) is scanned alongside `src/`, `benches/`, `examples/`
and `fuzz/` even though it is not literally inside any of those directories:
it is the only place `BITWUZLA_LIB_DIR`, `BITWUZLA_RUNTIME_LIB_DIRS` and
`GLAURUNG_BITWUZLA_TYPECHECK_ONLY` are actually read, and the task this
generator was built for explicitly wants `BITWUZLA_*` covered.

Usage::

    uv run python tools/gen_env_reference.py            # write
    uv run python tools/gen_env_reference.py --check    # exit 1 if stale
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass, field
from difflib import unified_diff
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = REPO_ROOT / "docs" / "reference" / "environment-variables.md"
GENERATOR_NAME = "tools/gen_env_reference.py"

# Directories to scan for Python-style reads (`os.environ`/`os.getenv`) and
# for building the Python constant-indirection map.
PY_DIRS = ("python/glaurung", "python/tests", "tools", "scripts")

# Directories to scan for Rust-style reads (`env::var`/`option_env!`) and for
# building the Rust constant-indirection map. `build.rs` is a single extra
# file at the repo root -- see the module docstring.
RS_DIRS = ("src", "benches", "examples", "fuzz")
RS_EXTRA_FILES = ("build.rs",)

# Directories to scan for GitHub Actions workflow `env:` blocks.
YAML_DIRS = (".github",)

#: Read generically, with no project-specific meaning, so excluded even
#: though they turn up in a handful of test/tooling reads.
GENERIC_EXCLUDE = frozenset({"HOME", "PATH"})

IDENT = r"[A-Za-z_][A-Za-z0-9_]*"

# --- Python read patterns ----------------------------------------------------
PY_ENVIRON_INDEX_RE = re.compile(
    r'os\.environ\[\s*[\'"](' + IDENT + r')[\'"]\s*\](?!\s*=(?!=))'
)
PY_ENVIRON_GET_RE = re.compile(r'os\.environ\.get\(\s*[\'"](' + IDENT + r')[\'"]')
PY_GETENV_RE = re.compile(r'os\.getenv\(\s*[\'"](' + IDENT + r')[\'"]')
# Bare-identifier indirection: `os.environ.get(SOME_CONST)`, `os.environ[SOME_CONST]`.
PY_ENVIRON_INDEX_IND_RE = re.compile(
    r"os\.environ\[\s*(" + IDENT + r")\s*\](?!\s*=(?!=))"
)
PY_ENVIRON_GET_IND_RE = re.compile(r"os\.environ\.get\(\s*(" + IDENT + r")\s*[,)]")
PY_GETENV_IND_RE = re.compile(r"os\.getenv\(\s*(" + IDENT + r")\s*[,)]")
# `NAME = "VALUE"` at column 0 -- the constant-definition side of the
# indirection above.
PY_CONST_DEF_RE = re.compile(r'^([A-Z][A-Z0-9_]*)\s*=\s*[\'"](' + IDENT + r')[\'"]\s*$')

# --- Rust read patterns -------------------------------------------------------
RS_ENV_VAR_LIT_RE = re.compile(r'(?:std::)?env::var(?:_os)?\(\s*"(' + IDENT + r')"')
RS_ENV_VAR_IND_RE = re.compile(
    r"(?:std::)?env::var(?:_os)?\(\s*(" + IDENT + r")\s*[,)]"
)
RS_OPTION_ENV_RE = re.compile(r'option_env!\(\s*"(' + IDENT + r')"')
RS_CONST_DEF_RE = re.compile(
    r"(?:pub(?:\(crate\))?\s+)?const\s+("
    + IDENT
    + r")\s*:\s*&'?\w*\s*str\s*=\s*\"([^\"]+)\""
)

SHA_LINE_RE = re.compile(
    r"^<!-- generated by [^ ]+ at [0-9a-f]+; do not edit -->$", re.MULTILINE
)
SHA_LINE_PLACEHOLDER = "<!-- generated by GENERATOR at SHA; do not edit -->"


def _short_sha() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _normalize(text: str) -> str:
    return SHA_LINE_RE.sub(SHA_LINE_PLACEHOLDER, text)


@dataclass
class Findings:
    #: variable name -> sorted set of repo-relative paths that read it.
    sites: dict[str, set[str]] = field(default_factory=dict)

    def add(self, name: str, path: Path, line_no: int) -> None:
        if name in GENERIC_EXCLUDE:
            return
        rel = path.relative_to(REPO_ROOT).as_posix()
        # Paths only: line numbers would make --check stale on every edit
        # near an env read, which is exactly the churn a generated reference
        # exists to avoid. `line_no` is kept in the signature for callers.
        del line_no
        self.sites.setdefault(name, set()).add(rel)


#: This generator's own module docstring spells out example calls
#: (`os.environ["X"]`, `env::var("X")`, ...) to document the patterns it
#: looks for. Those examples are themselves valid matches, so the file
#: would otherwise "find" a bogus variable named `X` in itself every run.
_SELF = Path(__file__).resolve()


def _iter_files(dirs: tuple[str, ...], suffixes: tuple[str, ...]) -> list[Path]:
    out: list[Path] = []
    for d in dirs:
        base = REPO_ROOT / d
        if not base.exists():
            continue
        for suffix in suffixes:
            out.extend(p for p in base.rglob(f"*{suffix}") if p.resolve() != _SELF)
    return sorted(set(out))


def _line_no(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


#: `for name, attr in (("GLAURUNG_X", "attr_x"), ...): ... os.getenv(name)` --
#: a table-driven read used by `llm/config.py`'s budget-env block. The outer
#: tuple literal is matched as one non-nested-parens run per inner tuple,
#: which is exact for this codebase's style (inner tuples never nest
#: further); a loop var used by `os.getenv`/`os.environ.get` within the next
#: 600 characters after the header is treated as consuming it.
FOR_TUPLE_HEADER_RE = re.compile(
    r"for\s+(" + IDENT + r")\s*,\s*" + IDENT + r"\s+in\s*\(\s*"
    r"((?:\([^()]*\)\s*,?\s*)+)\)\s*:"
)
TUPLE_FIRST_STR_RE = re.compile(r'\(\s*"(' + IDENT + r')"\s*,')


def _scan_for_loop_env_tuples(text: str, path: Path, findings: Findings) -> None:
    for header in FOR_TUPLE_HEADER_RE.finditer(text):
        loop_var = header.group(1)
        tail = text[header.end() : header.end() + 600]
        use = re.search(
            r"os\.(?:getenv|environ\.get)\(\s*" + re.escape(loop_var) + r"\b", tail
        )
        if not use:
            continue
        line_no = _line_no(text, header.end() + use.start())
        for name_m in TUPLE_FIRST_STR_RE.finditer(header.group(2)):
            findings.add(name_m.group(1), path, line_no)


def _scan_python(findings: Findings) -> None:
    files = _iter_files(PY_DIRS, (".py",))

    const_map: dict[str, str] = {}
    file_text: dict[Path, str] = {}
    for path in files:
        try:
            text = path.read_text(errors="ignore")
        except OSError:
            continue
        file_text[path] = text
        for line in text.splitlines():
            m = PY_CONST_DEF_RE.match(line)
            if m:
                const_map[m.group(1)] = m.group(2)

    for path, text in file_text.items():
        for pat in (PY_ENVIRON_INDEX_RE, PY_ENVIRON_GET_RE, PY_GETENV_RE):
            for m in pat.finditer(text):
                findings.add(m.group(1), path, _line_no(text, m.start()))
        for pat in (PY_ENVIRON_INDEX_IND_RE, PY_ENVIRON_GET_IND_RE, PY_GETENV_IND_RE):
            for m in pat.finditer(text):
                resolved = const_map.get(m.group(1))
                if resolved:
                    findings.add(resolved, path, _line_no(text, m.start()))
        _scan_for_loop_env_tuples(text, path, findings)


def _scan_rust(findings: Findings) -> None:
    files = _iter_files(RS_DIRS, (".rs",))
    files.extend(REPO_ROOT / f for f in RS_EXTRA_FILES if (REPO_ROOT / f).is_file())
    files = sorted(set(files))

    const_map: dict[str, str] = {}
    file_text: dict[Path, str] = {}
    for path in files:
        try:
            text = path.read_text(errors="ignore")
        except OSError:
            continue
        file_text[path] = text
        for line in text.splitlines():
            for m in RS_CONST_DEF_RE.finditer(line):
                const_map[m.group(1)] = m.group(2)

    for path, text in file_text.items():
        for m in RS_ENV_VAR_LIT_RE.finditer(text):
            findings.add(m.group(1), path, _line_no(text, m.start()))
        for m in RS_OPTION_ENV_RE.finditer(text):
            findings.add(m.group(1), path, _line_no(text, m.start()))
        for m in RS_ENV_VAR_IND_RE.finditer(text):
            resolved = const_map.get(m.group(1))
            if resolved:
                findings.add(resolved, path, _line_no(text, m.start()))


def _scan_yaml_env_blocks(findings: Findings) -> None:
    files = _iter_files(YAML_DIRS, (".yml", ".yaml"))
    key_re = re.compile(r"^\s*(" + IDENT + r"):")
    for path in files:
        try:
            lines = path.read_text(errors="ignore").splitlines()
        except OSError:
            continue
        i = 0
        while i < len(lines):
            if lines[i].strip() == "env:":
                env_indent = len(lines[i]) - len(lines[i].lstrip(" "))
                j = i + 1
                while j < len(lines):
                    candidate = lines[j]
                    if not candidate.strip():
                        j += 1
                        continue
                    indent = len(candidate) - len(candidate.lstrip(" "))
                    if indent <= env_indent:
                        break
                    if indent == env_indent + 2:
                        m = key_re.match(candidate)
                        if m:
                            findings.add(m.group(1), path, j + 1)
                    j += 1
            i += 1


def collect() -> Findings:
    findings = Findings()
    _scan_python(findings)
    _scan_rust(findings)
    _scan_yaml_env_blocks(findings)
    return findings


