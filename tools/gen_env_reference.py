def _truncate_paths(paths: list[str], limit: int = 3) -> str:
    shown = paths[:limit]
    text = ", ".join(f"`{p}`" for p in shown)
    if len(paths) > limit:
        text += f", … (+{len(paths) - limit} more)"
    return text


def render(findings: Findings) -> str:
    lines: list[str] = [
        "# Environment variables",
        "",
        "> **Kind:** reference · **Status:** generated",
        f"<!-- generated by {GENERATOR_NAME} at {_short_sha()}; do not edit -->",
        "",
        "Every environment variable this repository reads, found by walking "
        f"`{', '.join(PY_DIRS)}` for Python reads, `{', '.join(RS_DIRS)}` "
        "(plus `build.rs`) for Rust reads, and `.github` for workflow `env:` "
        "blocks -- see `tools/gen_env_reference.py` for the exact patterns "
        "and the one-hop constant indirection it resolves. A variable with "
        "no entry in the generator's `PURPOSES` dict is marked undocumented "
        "so the gap is visible rather than silently dropped. Regenerate "
        "with `uv run python tools/gen_env_reference.py`; `--check` fails "
        "the build when this file is stale.",
        "",
        f"{len(findings.sites)} variables found, "
        f"{sum(1 for k in findings.sites if k in PURPOSES)} documented.",
        "",
        "| Variable | Read in | Purpose |",
        "| --- | --- | --- |",
    ]
    for name in sorted(findings.sites):
        paths = sorted(findings.sites[name])
        purpose = PURPOSES.get(
            name, "(undocumented — add to PURPOSES in the generator)"
        )
        lines.append(f"| `{name}` | {_truncate_paths(paths)} | {purpose} |")
    lines.append("")

    unused_purposes = sorted(set(PURPOSES) - set(findings.sites))
    if unused_purposes:
        lines.append(
            "The following `PURPOSES` entries no longer match any read site "
            "found by the scan above (renamed or removed -- update the "
            "generator):"
        )
        lines.append("")
        for name in unused_purposes:
            lines.append(f"- `{name}`")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def generate() -> str:
    return render(collect())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the generated reference differs",
    )
    args = parser.parse_args(argv)

    content = generate()
    existing = OUT_PATH.read_text() if OUT_PATH.exists() else None

    if args.check:
        if existing is not None and _normalize(existing) == _normalize(content):
            return 0
        print(f"stale: {OUT_PATH.relative_to(REPO_ROOT)}", file=sys.stderr)
        old_lines = _normalize(existing or "").splitlines(keepends=True)
        new_lines = _normalize(content).splitlines(keepends=True)
        diff = unified_diff(
            old_lines, new_lines, fromfile="committed", tofile="generated"
        )
        sys.stderr.writelines(diff)
        print(f"\nrun: uv run python {GENERATOR_NAME}", file=sys.stderr)
        return 1

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(content)
    print(f"wrote {OUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
